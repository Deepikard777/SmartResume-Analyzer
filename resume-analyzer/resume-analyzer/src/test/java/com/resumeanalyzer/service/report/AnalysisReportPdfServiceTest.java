package com.resumeanalyzer.service.report;

import com.resumeanalyzer.dto.AnalysisResponse;
import com.resumeanalyzer.exception.ReportGenerationException;
import org.apache.pdfbox.Loader;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.text.PDFTextStripper;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * Unit tests for the PDF report renderer.
 *
 * The generated bytes are parsed back with PDFBox and the extracted text is asserted,
 * so these tests verify the actual document contents rather than just that a byte
 * array was produced.
 */
class AnalysisReportPdfServiceTest {

    private final AnalysisReportPdfService service = new AnalysisReportPdfService();

    private static final LocalDateTime GENERATED_AT = LocalDateTime.of(2026, 10, 11, 15, 30);

    private AnalysisResponse sampleAnalysis() {
        return AnalysisResponse.builder()
                .id(42L)
                .resumeId(3L)
                .resumeFileName("student_resume.pdf")
                .jobTitle("Full Stack Software Engineer")
                .companyName("Test Company")
                .atsScore(71)
                .scoreBreakdown(AnalysisResponse.ScoreBreakdown.builder()
                        .skillMatch(67).keywordMatch(62).relevance(62).structure(95).formatting(100).build())
                .matchedSkills(List.of("Java", "Spring Boot", "SQL"))
                .missingSkills(List.of("Docker", "AWS"))
                .optionalSkills(List.of("Kubernetes"))
                .matchedKeywords(List.of("java", "sql"))
                .missingKeywords(List.of("docker", "microservices"))
                .keywordCoverage(List.of(
                        AnalysisResponse.KeywordCoverage.builder().keyword("java").jobDescriptionCount(3)
                                .resumeCount(5).matched(true).flagged(true).inJobDescription(true)
                                .flagReason("Appears 5 times.").build(),
                        AnalysisResponse.KeywordCoverage.builder().keyword("docker").jobDescriptionCount(2)
                                .resumeCount(0).matched(false).flagged(false).inJobDescription(true).build()))
                .keywordStuffing(AnalysisResponse.KeywordStuffingInfo.builder()
                        .risk("MEDIUM")
                        .flaggedKeywords(List.of(AnalysisResponse.FlaggedKeyword.builder()
                                .keyword("java").frequency(5).reason("Appears 5 times.").build()))
                        .build())
                .structure(List.of(
                        AnalysisResponse.StructureCheck.builder().section("Contact Information")
                                .status("PASSED").message("Contact Information section detected.").build(),
                        AnalysisResponse.StructureCheck.builder().section("Internships")
                                .status("WARNING").message("No internships section detected.").build()))
                .recommendations(List.of(AnalysisResponse.Recommendation.builder()
                        .category("Skills").priority("HIGH")
                        .title("Address the required skills the job description asks for")
                        .detail("Docker and AWS were not found. Add evidence only if you genuinely have it.")
                        .relatedItems(List.of("Docker", "AWS"))
                        .source("RULE")
                        .build()))
                .createdAt(GENERATED_AT)
                .build();
    }

    private String textOf(byte[] pdf) throws IOException {
        try (PDDocument document = Loader.loadPDF(pdf)) {
            return new PDFTextStripper().getText(document);
        }
    }

    private int pageCount(byte[] pdf) throws IOException {
        try (PDDocument document = Loader.loadPDF(pdf)) {
            return document.getNumberOfPages();
        }
    }

    @Test
    @DisplayName("Generates a readable PDF containing every required section")
    void generatesCompleteReport() throws IOException {
        byte[] pdf = service.generate(sampleAnalysis(), "Asha Student", "asha@example.com", GENERATED_AT);

        assertThat(pdf).isNotEmpty();
        // %PDF magic number
        assertThat(new String(pdf, 0, 5, java.nio.charset.StandardCharsets.US_ASCII)).isEqualTo("%PDF-");

        String text = textOf(pdf);
        assertThat(text).contains("SmartResume Analyzer");
        assertThat(text).contains("Asha Student");
        assertThat(text).contains("asha@example.com");
        assertThat(text).contains("student_resume.pdf");
        assertThat(text).contains("Full Stack Software Engineer");
        assertThat(text).contains("Test Company");
        assertThat(text).contains("71 / 100");
        assertThat(text).contains("Skill match");
        assertThat(text).contains("Keyword match");
        assertThat(text).contains("Relevance");
        assertThat(text).contains("Docker");
        assertThat(text).contains("AWS");
        assertThat(text).contains("Kubernetes");
        assertThat(text).contains("Keyword frequency and coverage");
        assertThat(text).contains("Structure");
        assertThat(text).contains("Recommended improvements");
        assertThat(text).contains("11 Oct 2026");
    }

    @Test
    @DisplayName("Reports the repetition flag without penalising the count itself")
    void reportsRepetitionFlag() throws IOException {
        String text = textOf(service.generate(sampleAnalysis(), "Asha", "a@b.c", GENERATED_AT));

        assertThat(text).contains("Repeated");
        assertThat(text).contains("Missing");
        assertThat(text).contains("is not penalised by the score");
        // The raw counts must be visible so the reader can judge for themselves.
        assertThat(text).contains("In resume");
        assertThat(text).contains("In JD");
    }

    @Test
    @DisplayName("Long content flows onto multiple pages instead of being clipped")
    void longContentPaginates() throws IOException {
        List<AnalysisResponse.Recommendation> many = new ArrayList<>();
        for (int i = 0; i < 30; i++) {
            many.add(AnalysisResponse.Recommendation.builder()
                    .category("Skills").priority("HIGH")
                    .title("Recommendation number " + i + " about a specific measured gap")
                    .detail("This is a deliberately long explanation, repeated to force the layout engine to "
                            + "continue onto further pages. It describes what was measured and what to do about "
                            + "it, without asserting anything about the candidate that is not in the analysis.")
                    .relatedItems(List.of("Docker", "AWS"))
                    .source("RULE")
                    .build());
        }

        AnalysisResponse analysis = sampleAnalysis();
        analysis.setRecommendations(many);

        byte[] pdf = service.generate(analysis, "Asha", "asha@example.com", GENERATED_AT);

        assertThat(pageCount(pdf)).isGreaterThan(1);
        String text = textOf(pdf);
        assertThat(text).contains("Recommendation number 0");
        assertThat(text).contains("Recommendation number 29");
    }

    @Test
    @DisplayName("Typographic and accented characters are folded instead of breaking the renderer")
    void unicodeIsSanitised() {
        assertThat(AnalysisReportPdfService.sanitize("Curly \u201Cquotes\u201D and an em\u2014dash\u2026"))
                .isEqualTo("Curly \"quotes\" and an em-dash...");
        assertThat(AnalysisReportPdfService.sanitize("Jos\u00E9 \u00C1lvarez"))
                .isEqualTo("Jose Alvarez");
        assertThat(AnalysisReportPdfService.sanitize("5 \u00D7 3")).isEqualTo("5 x 3");
        assertThat(AnalysisReportPdfService.sanitize("a \u00B7 b")).isEqualTo("a - b");
        // Anything unmappable degrades to a placeholder rather than throwing.
        assertThat(AnalysisReportPdfService.sanitize("emoji \uD83D\uDE00 here")).isEqualTo("emoji ?? here");
    }

    @Test
    @DisplayName("A document full of unmappable text still renders")
    void hostileCharactersStillRender() throws IOException {
        AnalysisResponse analysis = sampleAnalysis();
        analysis.setJobTitle("R\u00F4le \u2014 D\u00E9veloppeur \uD83D\uDE80");
        analysis.setRecommendations(List.of(AnalysisResponse.Recommendation.builder()
                .category("Skills").priority("HIGH")
                .title("T\u00EDtulo with \u201Cquotes\u201D")
                .detail("Detail with an em\u2014dash, an ellipsis\u2026 and an emoji \uD83D\uDE80.")
                .relatedItems(List.of())
                .source("RULE")
                .build()));

        byte[] pdf = service.generate(analysis, "\u00C9l\u00E8ve", "e@example.com", GENERATED_AT);
        String text = textOf(pdf);

        assertThat(text).contains("Role");
        assertThat(text).contains("Developpeur");
        assertThat(text).contains("Titulo");
    }

    @Test
    @DisplayName("A null analysis raises a typed error instead of a NullPointerException")
    void nullAnalysisRaisesTypedError() {
        assertThatThrownBy(() -> service.generate(null, "A", "a@b.c", GENERATED_AT))
                .isInstanceOf(ReportGenerationException.class);
    }

    @Test
    @DisplayName("A minimal analysis with no optional data still produces a valid document")
    void minimalAnalysisRenders() throws IOException {
        AnalysisResponse minimal = AnalysisResponse.builder()
                .id(1L)
                .atsScore(null)
                .build();

        byte[] pdf = service.generate(minimal, null, null, GENERATED_AT);

        assertThat(pdf).isNotEmpty();
        String text = textOf(pdf);
        assertThat(text).contains("Overall ATS score");
        assertThat(text).contains("No score was stored");
    }
}
